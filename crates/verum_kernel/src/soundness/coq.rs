//! Coq constructor-closure schemas for the abstract kernel calculus.

use super::{RuleSpec, SchemaEvidence, SoundnessBackend, TypingSchema};

/// Coq emitter — implements [`SoundnessBackend`].
pub struct CoqBackend;

impl CoqBackend {
    /// Construct a fresh backend.
    pub fn new() -> Self {
        Self
    }
}

impl Default for CoqBackend {
    fn default() -> Self {
        Self::new()
    }
}

impl SoundnessBackend for CoqBackend {
    fn id(&self) -> &'static str {
        "coq"
    }

    fn schema_evidence(&self, rule: &RuleSpec) -> SchemaEvidence {
        if schema(rule).is_some() {
            SchemaEvidence::TypingDerivation
        } else {
            SchemaEvidence::Unavailable
        }
    }

    fn output_filename(&self) -> &'static str {
        "kernel_soundness.v"
    }

    fn render_preamble(&self) -> String {
        r#"(* kernel_soundness.v
   GENERATED by the Verum kernel schema exporter.
   Each theorem derives one abstract typing rule from the stated premises.
   Substitution is an opaque parameter. Metatheory references are unverified.
   Executable checker correspondence remains a separate proof obligation. *)
From Coq Require Import Strings.String Lists.List Arith.PeanoNat.
Import ListNotations.
Open Scope string_scope."#
            .into()
    }

    fn render_core_term_inductive(&self) -> String {
        "(* CoreTerm — kernel calculus syntax. *)\n\
         Inductive CoreTerm : Type :=\n  \
           | Var (name : string)\n  \
           | Universe (level : nat)\n  \
           | PropSort\n  \
           | Pi (binder : string) (domain codomain : CoreTerm)\n  \
           | Lam (binder : string) (domain body : CoreTerm)\n  \
           | App (head arg : CoreTerm)\n  \
           | Sigma (binder : string) (fst_ty snd_ty : CoreTerm)\n  \
           | Pair (fst snd : CoreTerm)\n  \
           | Fst (inner : CoreTerm)\n  \
           | Snd (inner : CoreTerm)\n  \
           | PathTy (carrier lhs rhs : CoreTerm)\n  \
           | PathOver (motive path lhs rhs : CoreTerm)\n  \
           | Refl (value : CoreTerm)\n  \
           | HComp (phi walls base : CoreTerm)\n  \
           | Transport (path value : CoreTerm)\n  \
           | Glue (carrier phi fiber equiv : CoreTerm)\n  \
           | Refine (base : CoreTerm) (binder : string) (predicate : CoreTerm)\n  \
           | Quotient (base equiv : CoreTerm)\n  \
           | QuotIntro (value base equiv : CoreTerm)\n  \
           | QuotElim (scrutinee motive case_fn respect : CoreTerm)\n  \
           | Inductive_ (path : string) (args : list CoreTerm)\n  \
           | Elim (scrutinee motive : CoreTerm) (cases : list CoreTerm)\n  \
           | SmtProof (solver_tag : string)\n  \
           | Axiom_ (name : string) (ty : CoreTerm) (framework : string)\n  \
           | EpsilonOf (articulation : CoreTerm)\n  \
           | AlphaOf (enactment : CoreTerm)\n  \
           | ModalBox (inner : CoreTerm)\n  \
           | ModalDiamond (inner : CoreTerm)\n  \
           | ModalBigAnd (components : list CoreTerm)\n  \
           | Shape (inner : CoreTerm)\n  \
           | Flat (inner : CoreTerm)\n  \
           | Sharp (inner : CoreTerm)."
            .to_string()
    }

    fn render_core_type_inductive(&self) -> String {
        "(* CoreType — structural type-head view. *)\n\
         Inductive CoreType : Type :=\n  \
           | UniverseTy (level : nat)\n  \
           | PiTy\n  \
           | SigmaTy\n  \
           | PathTyHead\n  \
           | RefineTy\n  \
           | GlueTy\n  \
           | InductiveTy (path : string)\n  \
           | OtherTy."
            .to_string()
    }

    fn render_kernel_rule_inductive(&self, rules: &[RuleSpec]) -> String {
        let mut out = String::new();

        out.push_str("(* KernelRule — the supported inference-rule names. *)\n");
        out.push_str("Inductive KernelRule : Type :=");
        for r in rules {
            out.push_str(&format!("\n    | {}", r.rule_name));
        }
        out.push_str(".\n\n");

        out.push_str(
            r#"Definition Ctx : Type := list (string * CoreTerm).

Fixpoint lookup (ctx : Ctx) (x : string) : option CoreTerm :=
  match ctx with
  | [] => None
  | (name, ty) :: rest => if String.eqb x name then Some ty else lookup rest x
  end.

Definition sortTerm (level : option nat) : CoreTerm :=
  match level with None => PropSort | Some i => Universe i end.

Parameter subst : string -> CoreTerm -> CoreTerm -> CoreTerm.

Definition QuotientFresh (name : string) (terms : list CoreTerm) : Prop :=
  forall term, In term terms -> forall value, subst name value term = term.

"#,
        );
        out.push_str(REFINEMENT_DEPTH_COQ);
        out.push('\n');
        out.push_str(iou_axioms_coq());
        out.push_str("\n\n");
        out.push_str("Inductive Typing : Ctx -> CoreTerm -> CoreTerm -> Prop :=\n  | T_prop : forall (Gamma : Ctx), Typing Gamma PropSort (Universe 0)");
        for signature in rules.iter().filter_map(schema) {
            out.push_str(&format!(
                "\n  | {} :\n    {}",
                signature.constructor, signature.proposition
            ));
        }
        out.push('.');
        out
    }

    fn render_rule_lemma(&self, rule: &RuleSpec) -> String {
        let note = format!("(* {} *)", rule.export_note());
        let Some(schema) = schema(rule) else {
            return note;
        };
        format!(
            "{note}\nLemma {} :\n  {}.\nProof. exact {}. Qed.",
            rule.lemma_name, schema.proposition, schema.constructor
        )
    }

    fn render_main_theorem(&self, rules: &[RuleSpec]) -> String {
        // Each branch reduces to the same proposition used for its constructor.
        let mut out = String::new();

        // 1. The per-rule type-body dispatch, materialised as
        //    `Soundness : KernelRule -> Prop`.
        out.push_str(
            "(* `Soundness rule` is the propositional shape of the per-rule    *)\n\
             (* lemma `K_<rule>_sound`.  Each branch quotes the rule's typing  *)\n\
             (* judgement; `kernel_soundness` aggregates them.                 *)\n",
        );
        out.push_str("Definition Soundness (rule : KernelRule) : Prop :=\n  match rule with\n");
        for r in rules {
            let Some(signature) = schema(r) else { continue };
            let body = signature.proposition;
            // Reflow body to one line — Coq is whitespace-flexible
            // inside forall.  The inline form keeps the match block
            // dense and readable.
            let one_line = body
                .replace("\n    ", " ")
                .replace("\n  ", " ")
                .replace('\n', " ");
            out.push_str(&format!("  | {} => {}\n", r.rule_name, one_line.trim(),));
        }
        out.push_str("  end.\n");

        // 2. The aggregate soundness theorem — case-analyses on
        //    `KernelRule` and dispatches each branch to its per-rule lemma.
        out.push_str(
            "\n(* **Kernel soundness** — case-analyses on `KernelRule` and *)\n\
             (* dispatches each branch to its `K_<rule>_sound` lemma.    *)\n",
        );
        // Conversion unfolds the dispatch at this rule without computing numeric bounds.
        out.push_str(
            "Theorem kernel_soundness : forall rule : KernelRule, Soundness rule.\n\
             Proof.\n  \
             intro rule. destruct rule.\n",
        );
        for r in rules {
            out.push_str(&format!("  - exact {}.\n", r.lemma_name));
        }
        out.push_str("Qed.\n");

        out
    }

    fn render_postscript(&self) -> String {
        String::from("(* End of kernel_soundness.v *)")
    }
}

pub(crate) fn iou_axioms_coq() -> &'static str {
    use std::sync::OnceLock;
    static CACHE: OnceLock<String> = OnceLock::new();
    CACHE
        .get_or_init(crate::soundness::render_iou_axioms_coq)
        .as_str()
}

const REFINEMENT_DEPTH_COQ: &str = r#"(* Finite-universe M-depth equations; modal depth and Rust correspondence are separate. *)
Fixpoint m_depth (term : CoreTerm) : nat := match term with
  | Var name => 0
  | Universe level => level
  | PropSort => 0
  | Pi binder a b => (Nat.max (m_depth a) (m_depth b))
  | Lam binder a b => (Nat.max (m_depth a) (m_depth b))
  | App a b => (Nat.max (m_depth a) (m_depth b))
  | Sigma binder a b => (Nat.max (m_depth a) (m_depth b))
  | Pair a b => (Nat.max (m_depth a) (m_depth b))
  | Fst a => (m_depth a)
  | Snd a => (m_depth a)
  | PathTy a b c => (Nat.max (Nat.max (m_depth a) (m_depth b)) (m_depth c))
  | PathOver a b c d => (Nat.max (Nat.max (Nat.max (m_depth a) (m_depth b)) (m_depth c)) (m_depth d))
  | Refl a => (m_depth a)
  | HComp a b c => (Nat.max (Nat.max (m_depth a) (m_depth b)) (m_depth c))
  | Transport a b => (Nat.max (m_depth a) (m_depth b))
  | Glue a b c d => (Nat.max (Nat.max (Nat.max (m_depth a) (m_depth b)) (m_depth c)) (m_depth d))
  | Refine a binder b => (Nat.max (m_depth a) (m_depth b))
  | Quotient a b => (Nat.max (m_depth a) (m_depth b))
  | QuotIntro a b c => (Nat.max (Nat.max (m_depth a) (m_depth b)) (m_depth c))
  | QuotElim a b c d => (Nat.max (Nat.max (Nat.max (m_depth a) (m_depth b)) (m_depth c)) (m_depth d))
  | Inductive_ name args => (1 + (fold_right Nat.max 0 (map m_depth args)))
  | Elim a b args => (Nat.max (Nat.max (m_depth a) (m_depth b)) (fold_right Nat.max 0 (map m_depth args)))
  | SmtProof name => 0
  | Axiom_ name a framework => (m_depth a)
  | EpsilonOf a => (m_depth a)
  | AlphaOf a => (m_depth a)
  | ModalBox a => (m_depth a)
  | ModalDiamond a => (m_depth a)
  | ModalBigAnd args => (fold_right Nat.max 0 (map m_depth args))
  | Shape a => (m_depth a)
  | Flat a => (m_depth a)
  | Sharp a => (m_depth a)
end.
"#;

/// Exact constructor proposition shared by the relation and its closure lemmas.
fn schema(rule: &RuleSpec) -> Option<TypingSchema> {
    if !rule.status.is_supported() {
        return None;
    }
    let (constructor, proposition) = match rule.rule_name.as_str() {
        "K_Var" => (
            "T_var",
            r#"forall (Gamma : Ctx) (x : string) (T : CoreTerm),
    lookup Gamma x = Some T -> Typing Gamma (Var x) T"#,
        ),
        "K_Univ" => (
            "T_univ",
            r#"forall (Gamma : Ctx) (i : nat),
    (i < Nat.pow 2 32 - 1)%nat ->
    Typing Gamma (Universe i) (Universe (S i))"#,
        ),
        "K_Pi_Form" => (
            "T_pi",
            r#"forall (Gamma : Ctx) (x : string) (A B : CoreTerm) (i : nat),
    Typing Gamma A (Universe i) ->
    Typing ((x, A) :: Gamma) B (Universe i) ->
    Typing Gamma (Pi x A B) (Universe i)"#,
        ),
        "K_Lam_Intro" => (
            "T_lam",
            r#"forall (Gamma : Ctx) (x : string) (A b B : CoreTerm) (i : nat),
    Typing Gamma A (Universe i) ->
    Typing ((x, A) :: Gamma) b B ->
    Typing Gamma (Lam x A b) (Pi x A B)"#,
        ),
        "K_App_Elim" => (
            "T_app",
            r#"forall (Gamma : Ctx) (f a : CoreTerm) (x : string) (A B : CoreTerm),
    Typing Gamma f (Pi x A B) -> Typing Gamma a A ->
    Typing Gamma (App f a) (subst x a B)"#,
        ),
        "K_Sigma_Form" => (
            "T_sigma",
            r#"forall (Gamma : Ctx) (x : string) (A B : CoreTerm) (i : nat),
    Typing Gamma A (Universe i) ->
    Typing ((x, A) :: Gamma) B (Universe i) ->
    Typing Gamma (Sigma x A B) (Universe i)"#,
        ),
        "K_Pair_Intro" => (
            "T_pair",
            r#"forall (Gamma : Ctx) (x : string) (A B a b : CoreTerm) (i : nat),
    Typing Gamma (Sigma x A B) (Universe i) ->
    Typing Gamma a A -> Typing Gamma b (subst x a B) ->
    Typing Gamma (Pair a b) (Sigma x A B)"#,
        ),
        "K_Fst_Elim" => (
            "T_fst",
            r#"forall (Gamma : Ctx) (p : CoreTerm) (x : string) (A B : CoreTerm),
    Typing Gamma p (Sigma x A B) -> Typing Gamma (Fst p) A"#,
        ),
        "K_Snd_Elim" => (
            "T_snd",
            r#"forall (Gamma : Ctx) (p : CoreTerm) (x : string) (A B : CoreTerm),
    Typing Gamma p (Sigma x A B) ->
    Typing Gamma (Snd p) (subst x (Fst p) B)"#,
        ),
        "K_Path_Ty_Form" => (
            "T_path_ty",
            r#"forall (Gamma : Ctx) (A a b : CoreTerm) (i : nat),
    Typing Gamma A (Universe i) -> Typing Gamma a A -> Typing Gamma b A ->
    Typing Gamma (PathTy A a b) (Universe i)"#,
        ),
        "K_Path_Over_Form" => (
            "T_path_over",
            r#"forall (Gamma : Ctx) (motive p lhs rhs carrier start finish : CoreTerm) (x : string) (i : nat),
    Typing Gamma motive (Pi x carrier (Universe i)) ->
    Typing Gamma p (PathTy carrier start finish) ->
    Typing Gamma lhs (App motive start) ->
    Typing Gamma rhs (App motive finish) ->
    Typing Gamma (PathOver motive p lhs rhs) (Universe i)"#,
        ),
        "K_Refl_Intro" => (
            "T_refl",
            r#"forall (Gamma : Ctx) (a A : CoreTerm),
    Typing Gamma a A -> Typing Gamma (Refl a) (PathTy A a a)"#,
        ),
        "K_Transp" => (
            "T_transp",
            r#"forall (Gamma : Ctx) (path value source target : CoreTerm) (i : nat),
        Typing Gamma source (Universe i) ->
        Typing Gamma target (Universe i) ->
        Typing Gamma path (PathTy (Universe i) source target) ->
        Typing Gamma value source ->
        Typing Gamma (Transport path value) target"#,
        ),
        "K_Refine" => (
            "T_refine",
            r#"forall (Gamma : Ctx) (base predicate : CoreTerm) (x : string) (i : nat),
    Typing Gamma base (Universe i) ->
    Typing ((x, base) :: Gamma) predicate PropSort ->
        m_depth predicate <= m_depth base ->
    Typing Gamma (Refine base x predicate) (Universe i)"#,
        ),
        "K_Refine_Intro" => (
            "T_refine_intro",
            r#"forall (Gamma : Ctx) (a base predicate witness : CoreTerm) (x : string) (i : nat),
    Typing Gamma (Refine base x predicate) (Universe i) ->
    Typing Gamma a base ->
    Typing Gamma witness (subst x a predicate) ->
    Typing Gamma a (Refine base x predicate)"#,
        ),
        "K_Refine_Erase" => (
            "T_refine_erase",
            r#"forall (Gamma : Ctx) (a base : CoreTerm) (x : string) (predicate : CoreTerm),
    Typing Gamma a (Refine base x predicate) -> Typing Gamma a base"#,
        ),
        "K_Quot_Form" => (
            "T_quot_form",
            r#"forall (Gamma : Ctx) (base equiv : CoreTerm) (i j : nat),
        QuotientFresh "x" [base] ->
        Typing Gamma base (Universe i) ->
        Typing Gamma equiv (Pi "x" base (Pi "y" base (Universe j))) ->
        Typing Gamma (Quotient base equiv) (Universe (Nat.max i j))"#,
        ),
        "K_Quot_Intro" => (
            "T_quot_intro",
            r#"forall (Gamma : Ctx) (value base equiv : CoreTerm) (i : nat),
        Typing Gamma (Quotient base equiv) (Universe i) ->
        Typing Gamma value base ->
        Typing Gamma (QuotIntro value base equiv) (Quotient base equiv)"#,
        ),
        "K_Quot_Elim" => (
            "T_quot_elim",
            r#"forall (Gamma : Ctx) (scrutinee motive case_fn respect base equiv result : CoreTerm) (i j : nat),
        QuotientFresh "q" [result] ->
        QuotientFresh "x" [base; equiv; result; case_fn] ->
        QuotientFresh "y" [base; equiv; result; case_fn] ->
        QuotientFresh "r" [base; equiv; result; case_fn] ->
        motive = Lam "q" (Quotient base equiv) result ->
        Typing Gamma (Quotient base equiv) (Universe j) ->
        Typing Gamma result (Universe i) ->
        Typing Gamma scrutinee (Quotient base equiv) ->
        Typing Gamma case_fn (Pi "x" base result) ->
        Typing Gamma respect (Pi "x" base (Pi "y" base (Pi "r"
          (App (App equiv (Var "x")) (Var "y"))
          (PathTy result (App case_fn (Var "x")) (App case_fn (Var "y")))))) ->
        Typing Gamma (QuotElim scrutinee motive case_fn respect) (App motive scrutinee)"#,
        ),
        "K_Universe_Ascent" => (
            "T_universe_ascent",
            r#"forall (Gamma : Ctx) (i : nat),
    (i < Nat.pow 2 32 - 1)%nat ->
    Typing Gamma (Universe i) (Universe (S i))"#,
        ),
        "K_Epsilon_Of" => (
            "T_epsilon_of",
            r#"forall (Gamma : Ctx) (articulation result : CoreTerm),
    Typing Gamma articulation result ->
    Typing Gamma (EpsilonOf articulation) result"#,
        ),
        "K_Alpha_Of" => (
            "T_alpha_of",
            r#"forall (Gamma : Ctx) (enactment result : CoreTerm),
    Typing Gamma enactment result ->
    Typing Gamma (AlphaOf enactment) result"#,
        ),
        "K_Modal_Box" => (
            "T_modal_box",
            r#"forall (Gamma : Ctx) (inner T : CoreTerm),
    Typing Gamma inner T -> Typing Gamma (ModalBox inner) PropSort"#,
        ),
        "K_Modal_Diamond" => (
            "T_modal_diamond",
            r#"forall (Gamma : Ctx) (inner T : CoreTerm),
    Typing Gamma inner T -> Typing Gamma (ModalDiamond inner) PropSort"#,
        ),
        "K_Modal_Big_And" => (
            "T_modal_big_and",
            r#"forall (Gamma : Ctx) (components : list CoreTerm) (typeOf : CoreTerm -> CoreTerm),
    (forall component, In component components -> Typing Gamma component (typeOf component)) ->
    Typing Gamma (ModalBigAnd components) PropSort"#,
        ),
        "K_Shape" => (
            "T_shape",
            r#"forall (Gamma : Ctx) (inner : CoreTerm) (level : option nat),
    Typing Gamma inner (sortTerm level) ->
    Typing Gamma (Shape inner) (sortTerm level)"#,
        ),
        "K_Flat" => (
            "T_flat",
            r#"forall (Gamma : Ctx) (inner : CoreTerm) (level : option nat),
    Typing Gamma inner (sortTerm level) ->
    Typing Gamma (Flat inner) (sortTerm level)"#,
        ),
        "K_Sharp" => (
            "T_sharp",
            r#"forall (Gamma : Ctx) (inner : CoreTerm) (level : option nat),
    Typing Gamma inner (sortTerm level) ->
    Typing Gamma (Sharp inner) (sortTerm level)"#,
        ),
        _ => return None,
    };
    Some(TypingSchema {
        constructor,
        proposition,
    })
}
