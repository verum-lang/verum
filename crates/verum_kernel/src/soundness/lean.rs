//! Lean constructor-closure schemas for the abstract kernel calculus.

use super::{RuleSpec, SchemaEvidence, SoundnessBackend, TypingSchema};

/// Lean 4 emitter — implements [`SoundnessBackend`].
pub struct LeanBackend;

impl LeanBackend {
    /// Construct a fresh backend.
    pub fn new() -> Self {
        Self
    }
}

impl Default for LeanBackend {
    fn default() -> Self {
        Self::new()
    }
}

impl SoundnessBackend for LeanBackend {
    fn id(&self) -> &'static str {
        "lean"
    }

    fn schema_evidence(&self, rule: &RuleSpec) -> SchemaEvidence {
        if schema(rule).is_some() {
            SchemaEvidence::TypingDerivation
        } else {
            SchemaEvidence::Unavailable
        }
    }

    fn output_filename(&self) -> &'static str {
        "KernelSoundness.lean"
    }

    fn render_preamble(&self) -> String {
        r#"/-!
# KernelSoundness.lean
GENERATED by the Verum kernel schema exporter.
Each theorem derives one abstract typing rule from the stated premises.
Substitution is an opaque parameter. Metatheory references are unverified.
Executable checker correspondence remains a separate proof obligation.
-/
namespace KernelSoundness"#
            .into()
    }

    fn render_core_term_inductive(&self) -> String {
        String::from(
            "/-- `CoreTerm` — kernel calculus syntax (mirror of\n\
             `verum_kernel::CoreTerm` at term.rs:31-377). -/\n\
             inductive CoreTerm : Type where\n  \
               | Var (name : String)\n  \
               | Universe (level : Nat)\n  \
               | PropSort\n  \
               | Pi (binder : String) (domain codomain : CoreTerm)\n  \
               | Lam (binder : String) (domain body : CoreTerm)\n  \
               | App (head arg : CoreTerm)\n  \
               | Sigma (binder : String) (fst_ty snd_ty : CoreTerm)\n  \
               | Pair (fst snd : CoreTerm)\n  \
               | Fst (inner : CoreTerm)\n  \
               | Snd (inner : CoreTerm)\n  \
               | PathTy (carrier lhs rhs : CoreTerm)\n  \
               | PathOver (motive path lhs rhs : CoreTerm)\n  \
               | Refl (value : CoreTerm)\n  \
               | HComp (phi walls base : CoreTerm)\n  \
               | Transport (path value : CoreTerm)\n  \
               | Glue (carrier phi fiber equiv : CoreTerm)\n  \
               | Refine (base : CoreTerm) (binder : String) (predicate : CoreTerm)\n  \
               | Quotient (base equiv : CoreTerm)\n  \
               | QuotIntro (value base equiv : CoreTerm)\n  \
               | QuotElim (scrutinee motive case_fn respect : CoreTerm)\n  \
               | Inductive_ (path : String) (args : List CoreTerm)\n  \
               | Elim (scrutinee motive : CoreTerm) (cases : List CoreTerm)\n  \
               | SmtProof (solver_tag : String)\n  \
               | Axiom_ (name : String) (ty : CoreTerm) (framework : String)\n  \
               | EpsilonOf (articulation : CoreTerm)\n  \
               | AlphaOf (enactment : CoreTerm)\n  \
               | ModalBox (inner : CoreTerm)\n  \
               | ModalDiamond (inner : CoreTerm)\n  \
               | ModalBigAnd (components : List CoreTerm)\n  \
               | Shape (inner : CoreTerm)\n  \
               | Flat (inner : CoreTerm)\n  \
               | Sharp (inner : CoreTerm)\n  \
               deriving Inhabited",
        )
    }

    fn render_core_type_inductive(&self) -> String {
        String::from(
            "/-- `CoreType` — structural type-head view (mirror of\n\
             `verum_kernel::CoreType` at term.rs:386-403). -/\n\
             inductive CoreType : Type where\n  \
               | UniverseTy (level : Nat)\n  \
               | PiTy\n  \
               | SigmaTy\n  \
               | PathTyHead\n  \
               | RefineTy\n  \
               | GlueTy\n  \
               | InductiveTy (path : String)\n  \
               | OtherTy\n  \
               deriving Inhabited",
        )
    }

    fn render_kernel_rule_inductive(&self, rules: &[RuleSpec]) -> String {
        let mut out = String::new();

        // 1. The supported-rule enum.  Stable text mirror of `KernelRule`.
        out.push_str(
            "/-- `KernelRule` — the supported inference-rule names. -/\n\
             inductive KernelRule : Type where",
        );
        for r in rules {
            out.push_str(&format!("\n  | {}", r.rule_name));
        }
        out.push_str("\n  deriving Inhabited\n\n");

        out.push_str(
            r#"abbrev Ctx := List (String × CoreTerm)

@[simp] def lookup : Ctx → String → Option CoreTerm
  | [], _ => none
  | (name, ty) :: rest, x => if x = name then some ty else lookup rest x

def sortTerm : Option Nat → CoreTerm
  | none => .PropSort
  | some i => .Universe i

opaque subst (x : String) (replacement body : CoreTerm) : CoreTerm

def QuotientFresh (name : String) (terms : List CoreTerm) : Prop :=
  ∀ term ∈ terms, ∀ value, subst name value term = term

"#,
        );
        out.push_str(REFINEMENT_DEPTH_LEAN);
        out.push('\n');
        out.push_str(iou_axioms_lean());
        out.push_str("\n\n");
        out.push_str("inductive Typing : Ctx → CoreTerm → CoreTerm → Prop where\n  | t_prop : ∀ (Γ : Ctx), Typing Γ CoreTerm.PropSort (CoreTerm.Universe 0)");
        for signature in rules.iter().filter_map(schema) {
            out.push_str(&format!(
                "\n  | {} :\n    {}",
                signature.constructor, signature.proposition
            ));
        }
        out
    }

    fn render_rule_lemma(&self, rule: &RuleSpec) -> String {
        let note = format!("-- {}", rule.export_note());
        let Some(schema) = schema(rule) else {
            return note;
        };
        format!(
            "{note}\ntheorem {} :\n  {} :=\n  @Typing.{}",
            rule.lemma_name, schema.proposition, schema.constructor
        )
    }

    fn render_main_theorem(&self, rules: &[RuleSpec]) -> String {
        // Each branch reduces to the same proposition used for its constructor.
        let mut out = String::new();

        // 1. The per-rule type-body dispatch, materialised as
        //    `Soundness : KernelRule → Prop`.
        out.push_str(
            "/-- `Soundness rule` is the propositional shape of the per-rule\n\
             lemma `K_<rule>_sound`.  Each branch quotes the rule's typing\n\
             judgement; `kernel_soundness` aggregates them. -/\n",
        );
        out.push_str("def Soundness : KernelRule → Prop\n");
        for r in rules {
            let Some(signature) = schema(r) else { continue };
            let body = signature.proposition;
            // Reflow the body onto a single line when possible — the
            // match-arm form is most readable that way.  Lean is
            // whitespace-flexible inside Π; collapsing `\n  ` to a
            // single space loses no information.
            let one_line = body
                .replace("\n      ", " ")
                .replace("\n    ", " ")
                .replace('\n', " ");
            out.push_str(&format!(
                "  | KernelRule.{} => {}\n",
                r.rule_name,
                one_line.trim(),
            ));
        }

        // 2. The aggregate soundness theorem — case-analyses on
        //    `KernelRule` and dispatches each branch to its per-rule lemma.
        out.push_str(
            "\n/-- **Kernel soundness** — case-analyses on `KernelRule` and\n\
             dispatches each branch to its `K_<rule>_sound` lemma. -/\n",
        );
        out.push_str(
            "theorem kernel_soundness : ∀ rule, Soundness rule := by\n  \
             intro rule\n  \
             cases rule\n",
        );
        for r in rules {
            out.push_str(&format!(
                "  case {} => exact {}\n",
                r.rule_name, r.lemma_name,
            ));
        }

        out
    }

    fn render_postscript(&self) -> String {
        String::from("end KernelSoundness")
    }
}

pub(crate) fn iou_axioms_lean() -> &'static str {
    use std::sync::OnceLock;
    static CACHE: OnceLock<String> = OnceLock::new();
    CACHE
        .get_or_init(crate::soundness::render_iou_axioms_lean)
        .as_str()
}

const REFINEMENT_DEPTH_LEAN: &str = r#"/-- Finite-universe projection of the Rust M-depth equations.
This is separate from modal depth and does not prove Rust correspondence. -/
def mDepth : CoreTerm → Nat
  | .Var name => 0
  | .Universe level => level
  | .PropSort => 0
  | .Pi binder a b => (max (mDepth a) (mDepth b))
  | .Lam binder a b => (max (mDepth a) (mDepth b))
  | .App a b => (max (mDepth a) (mDepth b))
  | .Sigma binder a b => (max (mDepth a) (mDepth b))
  | .Pair a b => (max (mDepth a) (mDepth b))
  | .Fst a => (mDepth a)
  | .Snd a => (mDepth a)
  | .PathTy a b c => (max (max (mDepth a) (mDepth b)) (mDepth c))
  | .PathOver a b c d => (max (max (max (mDepth a) (mDepth b)) (mDepth c)) (mDepth d))
  | .Refl a => (mDepth a)
  | .HComp a b c => (max (max (mDepth a) (mDepth b)) (mDepth c))
  | .Transport a b => (max (mDepth a) (mDepth b))
  | .Glue a b c d => (max (max (max (mDepth a) (mDepth b)) (mDepth c)) (mDepth d))
  | .Refine a binder b => (max (mDepth a) (mDepth b))
  | .Quotient a b => (max (mDepth a) (mDepth b))
  | .QuotIntro a b c => (max (max (mDepth a) (mDepth b)) (mDepth c))
  | .QuotElim a b c d => (max (max (max (mDepth a) (mDepth b)) (mDepth c)) (mDepth d))
  | .Inductive_ name args => (1 + ((args.map mDepth).foldl max 0))
  | .Elim a b args => (max (max (mDepth a) (mDepth b)) ((args.map mDepth).foldl max 0))
  | .SmtProof name => 0
  | .Axiom_ name a framework => (mDepth a)
  | .EpsilonOf a => (mDepth a)
  | .AlphaOf a => (mDepth a)
  | .ModalBox a => (mDepth a)
  | .ModalDiamond a => (mDepth a)
  | .ModalBigAnd args => ((args.map mDepth).foldl max 0)
  | .Shape a => (mDepth a)
  | .Flat a => (mDepth a)
  | .Sharp a => (mDepth a)
"#;

/// Exact constructor proposition shared by the relation and its closure lemmas.
fn schema(rule: &RuleSpec) -> Option<TypingSchema> {
    if !rule.status.is_supported() {
        return None;
    }
    let (constructor, proposition) = match rule.rule_name.as_str() {
        "K_Var" => (
            "t_var",
            r#"∀ {Γ : Ctx} {x : String} {T : CoreTerm},
      lookup Γ x = some T →
      Typing Γ (CoreTerm.Var x) T"#,
        ),
        "K_Univ" => (
            "t_univ",
            r#"∀ (Γ : Ctx) (i : Nat),
    i < 2^32 - 1 →
      Typing Γ (CoreTerm.Universe i) (CoreTerm.Universe (i + 1))"#,
        ),
        "K_Pi_Form" => (
            "t_pi",
            r#"∀ {Γ : Ctx} {x : String} {A B : CoreTerm} {i : Nat},
      Typing Γ A (CoreTerm.Universe i) →
      Typing ((x, A) :: Γ) B (CoreTerm.Universe i) →
      Typing Γ (CoreTerm.Pi x A B) (CoreTerm.Universe i)"#,
        ),
        "K_Lam_Intro" => (
            "t_lam",
            r#"∀ {Γ : Ctx} {x : String} {A b B : CoreTerm} {i : Nat},
      Typing Γ A (CoreTerm.Universe i) →
      Typing ((x, A) :: Γ) b B →
      Typing Γ (CoreTerm.Lam x A b) (CoreTerm.Pi x A B)"#,
        ),
        "K_App_Elim" => (
            "t_app",
            r#"∀ {Γ : Ctx} {f a : CoreTerm} {x : String} {A B : CoreTerm},
      Typing Γ f (CoreTerm.Pi x A B) →
      Typing Γ a A →
      Typing Γ (CoreTerm.App f a) (subst x a B)"#,
        ),
        "K_Sigma_Form" => (
            "t_sigma",
            r#"∀ {Γ : Ctx} {x : String} {A B : CoreTerm} {i : Nat},
      Typing Γ A (CoreTerm.Universe i) →
      Typing ((x, A) :: Γ) B (CoreTerm.Universe i) →
      Typing Γ (CoreTerm.Sigma x A B) (CoreTerm.Universe i)"#,
        ),
        "K_Pair_Intro" => (
            "t_pair",
            r#"∀ {Γ : Ctx} {x : String} {A B a b : CoreTerm} {i : Nat},
      Typing Γ (CoreTerm.Sigma x A B) (CoreTerm.Universe i) →
      Typing Γ a A →
      Typing Γ b (subst x a B) →
      Typing Γ (CoreTerm.Pair a b) (CoreTerm.Sigma x A B)"#,
        ),
        "K_Fst_Elim" => (
            "t_fst",
            r#"∀ {Γ : Ctx} {p : CoreTerm} {x : String} {A B : CoreTerm},
      Typing Γ p (CoreTerm.Sigma x A B) →
      Typing Γ (CoreTerm.Fst p) A"#,
        ),
        "K_Snd_Elim" => (
            "t_snd",
            r#"∀ {Γ : Ctx} {p : CoreTerm} {x : String} {A B : CoreTerm},
      Typing Γ p (CoreTerm.Sigma x A B) →
      Typing Γ (CoreTerm.Snd p) (subst x (CoreTerm.Fst p) B)"#,
        ),
        "K_Path_Ty_Form" => (
            "t_path_ty",
            r#"∀ {Γ : Ctx} {A a b : CoreTerm} {i : Nat},
      Typing Γ A (CoreTerm.Universe i) →
      Typing Γ a A →
      Typing Γ b A →
      Typing Γ (CoreTerm.PathTy A a b) (CoreTerm.Universe i)"#,
        ),
        "K_Path_Over_Form" => (
            "t_path_over",
            r#"∀ {Γ : Ctx} {motive p lhs rhs carrier start finish : CoreTerm} {x : String} {i : Nat},
    Typing Γ motive (CoreTerm.Pi x carrier (CoreTerm.Universe i)) →
    Typing Γ p (CoreTerm.PathTy carrier start finish) →
    Typing Γ lhs (CoreTerm.App motive start) →
    Typing Γ rhs (CoreTerm.App motive finish) →
    Typing Γ (CoreTerm.PathOver motive p lhs rhs) (CoreTerm.Universe i)"#,
        ),
        "K_Refl_Intro" => (
            "t_refl",
            r#"∀ {Γ : Ctx} {a A : CoreTerm},
      Typing Γ a A →
      Typing Γ (CoreTerm.Refl a) (CoreTerm.PathTy A a a)"#,
        ),
        "K_Transp" => (
            "t_transp",
            r#"∀ {Γ : Ctx} {path value source target : CoreTerm} {i : Nat},
        Typing Γ source (CoreTerm.Universe i) →
        Typing Γ target (CoreTerm.Universe i) →
        Typing Γ path (CoreTerm.PathTy (CoreTerm.Universe i) source target) →
        Typing Γ value source →
        Typing Γ (CoreTerm.Transport path value) target"#,
        ),
        "K_Refine" => (
            "t_refine",
            r#"∀ {Γ : Ctx} {base predicate : CoreTerm} {x : String} {i : Nat},
      Typing Γ base (CoreTerm.Universe i) →
      Typing ((x, base) :: Γ) predicate CoreTerm.PropSort →
        mDepth predicate ≤ mDepth base →
      Typing Γ (CoreTerm.Refine base x predicate) (CoreTerm.Universe i)"#,
        ),
        "K_Refine_Intro" => (
            "t_refine_intro",
            r#"∀ {Γ : Ctx} {a base predicate witness : CoreTerm} {x : String} {i : Nat},
    Typing Γ (CoreTerm.Refine base x predicate) (CoreTerm.Universe i) →
    Typing Γ a base →
    Typing Γ witness (subst x a predicate) →
    Typing Γ a (CoreTerm.Refine base x predicate)"#,
        ),
        "K_Refine_Erase" => (
            "t_refine_erase",
            r#"∀ {Γ : Ctx} {a base : CoreTerm} {x : String} {predicate : CoreTerm},
      Typing Γ a (CoreTerm.Refine base x predicate) →
      Typing Γ a base"#,
        ),
        "K_Quot_Form" => (
            "t_quot_form",
            r#"∀ {Γ : Ctx} {base equiv : CoreTerm} {i j : Nat},
        QuotientFresh "x" [base] →
        Typing Γ base (CoreTerm.Universe i) →
        Typing Γ equiv (CoreTerm.Pi "x" base (CoreTerm.Pi "y" base (CoreTerm.Universe j))) →
        Typing Γ (CoreTerm.Quotient base equiv) (CoreTerm.Universe (max i j))"#,
        ),
        "K_Quot_Intro" => (
            "t_quot_intro",
            r#"∀ {Γ : Ctx} {value base equiv : CoreTerm} {i : Nat},
        Typing Γ (CoreTerm.Quotient base equiv) (CoreTerm.Universe i) →
        Typing Γ value base →
        Typing Γ (CoreTerm.QuotIntro value base equiv) (CoreTerm.Quotient base equiv)"#,
        ),
        "K_Quot_Elim" => (
            "t_quot_elim",
            r#"∀ {Γ : Ctx} {scrutinee motive case_fn respect base equiv result : CoreTerm} {i j : Nat},
        QuotientFresh "q" [result] →
        QuotientFresh "x" [base, equiv, result, case_fn] →
        QuotientFresh "y" [base, equiv, result, case_fn] →
        QuotientFresh "r" [base, equiv, result, case_fn] →
        motive = CoreTerm.Lam "q" (CoreTerm.Quotient base equiv) result →
        Typing Γ (CoreTerm.Quotient base equiv) (CoreTerm.Universe j) →
        Typing Γ result (CoreTerm.Universe i) →
        Typing Γ scrutinee (CoreTerm.Quotient base equiv) →
        Typing Γ case_fn (CoreTerm.Pi "x" base result) →
        Typing Γ respect (CoreTerm.Pi "x" base (CoreTerm.Pi "y" base (CoreTerm.Pi "r"
          (CoreTerm.App (CoreTerm.App equiv (CoreTerm.Var "x")) (CoreTerm.Var "y"))
          (CoreTerm.PathTy result (CoreTerm.App case_fn (CoreTerm.Var "x")) (CoreTerm.App case_fn (CoreTerm.Var "y")))))) →
        Typing Γ (CoreTerm.QuotElim scrutinee motive case_fn respect) (CoreTerm.App motive scrutinee)"#,
        ),
        "K_Universe_Ascent" => (
            "t_universe_ascent",
            r#"∀ {Γ : Ctx} {i : Nat},
    i < 2^32 - 1 →
      Typing Γ (CoreTerm.Universe i) (CoreTerm.Universe (i + 1))"#,
        ),
        "K_Epsilon_Of" => (
            "t_epsilon_of",
            r#"∀ {Γ : Ctx} {articulation result : CoreTerm},
      Typing Γ articulation result →
      Typing Γ (CoreTerm.EpsilonOf articulation) result"#,
        ),
        "K_Alpha_Of" => (
            "t_alpha_of",
            r#"∀ {Γ : Ctx} {enactment result : CoreTerm},
      Typing Γ enactment result →
      Typing Γ (CoreTerm.AlphaOf enactment) result"#,
        ),
        "K_Modal_Box" => (
            "t_modal_box",
            r#"∀ {Γ : Ctx} {inner T : CoreTerm},
      Typing Γ inner T →
      Typing Γ (CoreTerm.ModalBox inner) CoreTerm.PropSort"#,
        ),
        "K_Modal_Diamond" => (
            "t_modal_diamond",
            r#"∀ {Γ : Ctx} {inner T : CoreTerm},
      Typing Γ inner T →
      Typing Γ (CoreTerm.ModalDiamond inner) CoreTerm.PropSort"#,
        ),
        "K_Modal_Big_And" => (
            "t_modal_big_and",
            r#"∀ {Γ : Ctx} {components : List CoreTerm} {typeOf : CoreTerm → CoreTerm},
    (∀ component ∈ components, Typing Γ component (typeOf component)) →
    Typing Γ (CoreTerm.ModalBigAnd components) CoreTerm.PropSort"#,
        ),
        "K_Shape" => (
            "t_shape",
            r#"∀ {Γ : Ctx} {inner : CoreTerm} {level : Option Nat},
    Typing Γ inner (sortTerm level) →
    Typing Γ (CoreTerm.Shape inner) (sortTerm level)"#,
        ),
        "K_Flat" => (
            "t_flat",
            r#"∀ {Γ : Ctx} {inner : CoreTerm} {level : Option Nat},
    Typing Γ inner (sortTerm level) →
    Typing Γ (CoreTerm.Flat inner) (sortTerm level)"#,
        ),
        "K_Sharp" => (
            "t_sharp",
            r#"∀ {Γ : Ctx} {inner : CoreTerm} {level : Option Nat},
    Typing Γ inner (sortTerm level) →
    Typing Γ (CoreTerm.Sharp inner) (sortTerm level)"#,
        ),
        _ => return None,
    };
    Some(TypingSchema {
        constructor,
        proposition,
    })
}
